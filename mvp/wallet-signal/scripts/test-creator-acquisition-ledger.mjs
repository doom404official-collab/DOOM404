import assert from 'node:assert/strict';
import {summarizeCreatorAcquisitionLedger} from '../lib/creatorAcquisitionLedger.mjs';
const mint='98kfF7rmsg1QDUEoCqNE7g7M1FdrTt92TEp2CLzypump';
const creator='6RKsroTt2NgJvyUyhUcKqANrpHwDw6eE52X9TMBsQ7WC';
const make=(signature,instructionIndex,type,amountRaw,extra={})=>({signature,instructionIndex,type,amountRaw,mint,creator,timestamp:1700000000,independentlyVerified:true,instructionVerified:true,...extra});
const buy=make('buy',0,'PURCHASE','100',{settlementVerified:true});
const sell=make('sell',1,'VERIFIED_SALE','40',{settlementVerified:true});
const internal=make('internal',2,'INTERNAL_TRANSFER','25',{bothWalletsAttributed:true});
const result=summarizeCreatorAcquisitionLedger({mint,creator,events:[buy,buy,sell,internal],historyComplete:true,attributionComplete:true});
assert.equal(result.acceptedCount,3);
assert.equal(result.totalAcquiredRaw,'100');
assert.equal(result.verifiedSoldRaw,'40');
assert.equal(result.reconciledRemainingRaw,'60');
assert.equal(result.sellThroughPct,40);
assert.equal(result.scoreEligible,true);
const missing=summarizeCreatorAcquisitionLedger({mint,creator,events:[buy,sell]});
assert.equal(missing.scoreEligible,false);
assert.equal(missing.sellThroughPct,null);
const unverified=summarizeCreatorAcquisitionLedger({mint,creator,events:[make('bad',0,'PURCHASE','200')]});
assert.equal(unverified.acceptedCount,0);
assert.equal(unverified.rejected.length,1);
const zero=summarizeCreatorAcquisitionLedger({mint,creator,events:[],historyComplete:true,attributionComplete:true});
assert.equal(zero.scoreEligible,false);
assert.equal(zero.sellThroughPct,null);
console.log('creator acquisition ledger tests passed');
