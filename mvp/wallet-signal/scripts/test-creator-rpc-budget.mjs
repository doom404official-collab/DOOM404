import assert from 'node:assert/strict';
import { createCreatorHistoryBudget } from '../lib/creatorHistoryBudget.mjs';
import { createSolanaRpcAdapter } from '../lib/creatorOriginRpc.mjs';
const mint='98kfF7rmsg1QDUEoCqNE7g7M1FdrTt92TEp2CLzypump';
let calls=0;
const fetchImpl=async()=>{calls++;return {ok:true,status:200,json:async()=>({result:[]})}};
const budget=createCreatorHistoryBudget({maxRequests:2,minIntervalMs:0});
const rpc=createSolanaRpcAdapter({rpcUrl:'https://example.com/rpc',fetchImpl,sharedBudget:budget,minIntervalMs:0});
await rpc.lookupSignaturePage(mint);
await rpc.lookupSignaturePage(mint);
await assert.rejects(()=>rpc.lookupSignaturePage(mint),/CREATOR_REQUEST_BUDGET_EXHAUSTED/);
assert.equal(calls,2);
assert.equal(budget.used,2);
let retryCalls=0;
const retryBudget=createCreatorHistoryBudget({maxRequests:2,minIntervalMs:0});
const retryRpc=createSolanaRpcAdapter({rpcUrl:'https://example.com/rpc',sharedBudget:retryBudget,minIntervalMs:0,sleep:async()=>{},fetchImpl:async()=>{retryCalls++;return retryCalls===1?{status:429,headers:{get:()=>null}}:{ok:true,status:200,json:async()=>({result:[]})}}});
await retryRpc.lookupSignaturePage(mint);
assert.equal(retryBudget.used,2);
console.log('creator shared RPC budget tests passed');
